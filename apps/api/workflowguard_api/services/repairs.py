from __future__ import annotations

import uuid

from sqlalchemy import desc, func, select
from sqlalchemy.orm import Session
from workflow_core.canonical.models import Workflow
from workflow_core.costing import CostEstimator
from workflow_core.evaluation import SemanticEvaluationEngine
from workflow_core.repair import DeterministicRepairEngine, RepairPatch, RepairPatchApplier
from workflow_core.testing import DeterministicTestGenerator, WorkflowTestRunner
from workflow_core.validation import ValidationEngine

from workflowguard_api.ai.providers import AIProviderError, AIProviderUnavailable
from workflowguard_api.ai.repair import RepairProvider, repair_provider_from_settings
from workflowguard_api.core.config import get_settings
from workflowguard_api.models.db import RepairProposalRecord, RepairValidationResultRecord
from workflowguard_api.services.costs import CostService
from workflowguard_api.services.execution import build_engine
from workflowguard_api.services.workflows import WorkflowService


class RepairProposalNotFoundError(LookupError):
    pass


class RepairService:
    def __init__(self, db: Session, ai_provider: RepairProvider | None = None) -> None:
        self.db = db
        self.workflow_service = WorkflowService(db)
        self.cost_service = CostService(db)
        self.repairer = DeterministicRepairEngine()
        self.applier = RepairPatchApplier()
        self.ai_provider = ai_provider

    def generate(self, workflow_id: uuid.UUID, finding: dict | None = None, *, use_ai: bool = True) -> RepairProposalRecord:
        record = self.workflow_service.get_workflow(workflow_id)
        version = self.workflow_service.get_current_version(record)
        workflow = Workflow.model_validate(version.canonical_json).model_copy(update={"id": str(record.id)})
        patch = self._build_patch(workflow, finding, use_ai=use_ai)
        preview = self._preview(workflow, patch)
        proposal = RepairProposalRecord(
            workflow_id=record.id,
            version_id=version.id,
            finding_id=patch.finding_id or None,
            status="proposed",
            patch_json=patch.model_dump(mode="json"),
            preview_json=preview,
            safety_flags=preview["safety_flags"],
        )
        self.db.add(proposal)
        self.db.flush()
        self.db.add(
            RepairValidationResultRecord(
                repair_proposal_id=proposal.id,
                result_type="preview",
                result_json=preview,
            )
        )
        self.db.commit()
        self.db.refresh(proposal)
        return proposal

    def _build_patch(self, workflow: Workflow, finding: dict | None, *, use_ai: bool) -> RepairPatch:
        if not use_ai:
            patch = self.repairer.propose(workflow, finding)
            patch.safety_notes.append("Generated deterministically because AI was disabled for this request.")
            return patch
        try:
            provider = self.ai_provider or repair_provider_from_settings(get_settings())
            patch = provider.generate_patch(workflow, finding)
            patch.safety_notes.append(f"Generated by AI provider {provider.provider_name}; schema-validated before preview.")
            return patch
        except (AIProviderUnavailable, AIProviderError) as exc:
            patch = self.repairer.propose(workflow, finding)
            patch.safety_notes.append(f"AI repair unavailable; deterministic fallback used: {exc}")
            return patch

    def list(self, workflow_id: uuid.UUID) -> list[RepairProposalRecord]:
        self.workflow_service.get_workflow(workflow_id)
        return list(
            self.db.execute(
                select(RepairProposalRecord)
                .where(RepairProposalRecord.workflow_id == workflow_id)
                .order_by(desc(RepairProposalRecord.created_at))
            )
            .scalars()
            .all()
        )

    def get(self, proposal_id: uuid.UUID) -> RepairProposalRecord:
        proposal = self.db.get(RepairProposalRecord, proposal_id)
        if proposal is None:
            raise RepairProposalNotFoundError(str(proposal_id))
        return proposal

    def accept(self, proposal_id: uuid.UUID) -> RepairProposalRecord:
        proposal = self.get(proposal_id)
        if proposal.status != "proposed":
            return proposal
        record = self.workflow_service.get_workflow(proposal.workflow_id)
        version = self.workflow_service.get_current_version(record)
        workflow = Workflow.model_validate(version.canonical_json).model_copy(update={"id": str(record.id)})
        patch = RepairPatch.model_validate(proposal.patch_json)
        candidate = self.applier.apply(workflow, patch)
        accepted_version = self.workflow_service.create_version_from_canonical(record.id, candidate)
        self.workflow_service.validate(record.id)
        proposal.status = "accepted"
        proposal.accepted_version_id = accepted_version.id
        proposal.preview_json = self._preview(candidate, patch)
        self.db.commit()
        self.db.refresh(proposal)
        return proposal

    def reject(self, proposal_id: uuid.UUID, reason: str | None = None) -> RepairProposalRecord:
        proposal = self.get(proposal_id)
        proposal.status = "rejected"
        proposal.preview_json.setdefault("rejection", reason or "Rejected by user.")
        self.db.commit()
        self.db.refresh(proposal)
        return proposal

    def dashboard_metrics(self) -> dict[str, int]:
        open_count = (
            self.db.scalar(select(func.count(RepairProposalRecord.id)).where(RepairProposalRecord.status == "proposed"))
            or 0
        )
        return {"open_repair_proposals": int(open_count)}

    def _preview(self, workflow: Workflow, patch: RepairPatch) -> dict:
        candidate = self.applier.apply(workflow, patch)
        validation = ValidationEngine().validate(candidate)
        evaluation = SemanticEvaluationEngine().evaluate(
            candidate,
            structural_score=round(validation.structural_quality_score),
            validation_findings=validation.findings,
        )
        tests = DeterministicTestGenerator().generate(candidate).tests[:8]
        runner = WorkflowTestRunner(build_engine())
        runs = []
        for test in tests:
            runs.append(runner.run(candidate, test, all_tests=tests, prior_runs=runs))
        before_cost = self.cost_service._pricing_catalog()

        estimate = CostEstimator(before_cost).estimate(candidate)
        return {
            "before": {"workflow_id": workflow.id, "node_count": len(workflow.nodes), "edge_count": len(workflow.edges)},
            "after": {"workflow_id": candidate.id, "node_count": len(candidate.nodes), "edge_count": len(candidate.edges)},
            "validation": {
                "structural_quality_score": validation.structural_quality_score,
                "findings": [finding.model_dump(mode="json") for finding in validation.findings],
            },
            "evaluation": {
                "overall_score": evaluation.overall_score,
                "dimension_scores": [score.model_dump(mode="json") for score in evaluation.dimension_scores],
                "findings": [finding.model_dump(mode="json") for finding in evaluation.findings],
            },
            "tests": {
                "total": len(runs),
                "passed": sum(1 for run in runs if run.status == "PASSED"),
                "failed": sum(1 for run in runs if run.status == "FAILED"),
                "error": sum(1 for run in runs if run.status == "ERROR"),
                "coverage": runs[-1].coverage.model_dump(mode="json") if runs and runs[-1].coverage else {},
            },
            "cost": {
                "cost_per_run": estimate.cost_per_run,
                "monthly_cost": estimate.monthly_cost,
                "assumptions": estimate.assumptions,
            },
            "safety_flags": patch.behavior_changes,
        }
